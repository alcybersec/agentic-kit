#!/usr/bin/env bash
# PreToolUse/Edit,Write,NotebookEdit,MultiEdit. Exclusive per-role path ownership.
#
# The role comes from the payload's `agent_type`, which Claude Code sets to the
# subagent's frontmatter `name` — the role name for a kit role card. That is a
# deliberate change from the first design (2026-10-02), where this script was rendered
# into the project and registered by each role card's frontmatter `hooks:` block with
# the role as $1. Frontmatter hooks are SKIPPED until the workspace is trusted and a
# `-p` session never counts as trusted, so in a fresh clone and in every
# non-interactive run the guard was absent while the design spec said ownership was
# enforced. A plugin hook has no such dependency: verified firing inside a subagent in
# an untrusted checkout.
#
# Two rules fall out of reading the role from the payload rather than being arranged:
#
#   * No `agent_type` means the main thread — the Orchestrator, which owns no paths and
#     legitimately writes the dispatch state, the register and the gate bundles. It is
#     never guarded, and now structurally so rather than by a registration choice.
#   * An `agent_type` naming no role in the lock (`Explore`, `general-purpose`, any
#     project's own subagent) is not ours to police. Exit 0: an ownership map describes
#     the roles it lists and nothing else.
#
# Not a containment boundary (design spec §6.2): it matches the file tools only, so a
# role can still reach another's tree through Bash.
set -uo pipefail
# Resolve the library relative to this script, not ${CLAUDE_PLUGIN_ROOT}: under
# `set -u` an unset variable would error before the inertness check could run.
_kit_dir="${BASH_SOURCE[0]%/*}"; [ "$_kit_dir" != "${BASH_SOURCE[0]}" ] || _kit_dir=.
# shellcheck source=lib/kitlock.sh
source "$_kit_dir/lib/kitlock.sh" || exit 0
kit_init

role=$(kit_in '.agent_type | strings')
[ -n "$role" ] || exit 0          # main thread: the Orchestrator is not guarded

# Only a role the profile describes. `jq -e` to distinguish "no such role" from a role
# whose `owns` happens to be empty.
jq -e --arg r "$role" '[.roles[]? | select(.name == $r)] | length > 0' \
  "$KIT_LOCK" >/dev/null 2>&1 || exit 0

path=$(kit_in '.tool_input.file_path | strings')
[ -n "$path" ] || exit 0
kit_candidates "$path" "$(kit_in '.cwd | strings')" || exit 0   # outside the project

critical=$(kit_q '.critical[]?')
veto=$(jq -r '.roles[]? | select(.veto == true) | .name | strings' "$KIT_LOCK" 2>/dev/null)
mine=$(jq -r --arg r "$role" '.roles[]? | select(.name==$r) | .owns[]? | strings' "$KIT_LOCK" 2>/dev/null)
others=$(jq -r --arg r "$role" '.roles[]? | select(.name!=$r) | .name as $n | .owns[]? | strings | "\($n)|\(.)"' "$KIT_LOCK" 2>/dev/null)
all_cands=("${KIT_CANDS[@]}")

# Every spelling is judged on its own: a symlink inside my tree that points into
# another role's is two candidates, and the second one must not be excused by the first.
for rel in "${all_cands[@]}"; do
  KIT_CANDS=("$rel")

  # This role's own memory is writable. It is also where Claude Code puts a subagent's
  # own `memory: project` directory, which is the same path by design.
  case "$rel" in ".claude/agent-memory/$role/"*) continue ;; esac

  # Critical paths: the veto role holds these outright, wherever they sit in the
  # ownership map. Ownership is directory-granular, so a kill switch or a permission
  # table lives with the code that reads it and the role that must guard it cannot own
  # the directory. Checked BEFORE ownership in both directions: every other role is
  # refused even when it owns the surrounding tree, and the veto role is allowed even
  # though it does not.
  if [ -n "$critical" ] && kit_match_glob "$critical"; then
    if [ -n "$veto" ] && [ "$role" = "$veto" ]; then
      continue
    fi
    kit_deny "Blocked: ${rel} is a critical path (matched '${KIT_MATCHED}' in the profile's \`critical\` list). Only \`${veto}\` may change it, whoever owns the directory around it. Put the change you need in your handoff note and ask the Orchestrator to route it to ${veto}."
  fi

  # Refused for every role, whatever the ownership map says.
  case "$rel" in
    .claude/agent-memory/*)
      owner="${rel#.claude/agent-memory/}"; owner="${owner%%/*}"
      kit_deny "Blocked: ${rel} is ${owner}'s agent memory. Keep your own facts in .claude/agent-memory/${role}/." ;;
    .claude/agents/*)
      kit_deny "Blocked: role cards are generated by the installer, not written by agents. Ask the user to re-render the kit (CLAUDE.md, section Kit) if a role needs changing." ;;
    # The guard must protect itself. Every refusal above is only as strong as the files
    # these lines cover: one Edit of the lock it reads the ownership map from disarms
    # ownership for every role at once -- the shortest route to self-expansion there is,
    # and the same argument that refuses strategy.md below. `.claude/hooks/*` stays in
    # the list although this guard no longer lives there: a project may keep hooks of
    # its own, and they are no more an agent's to edit than these are.
    .claude/hooks/*)
      kit_deny "Blocked: ${rel} is an enforcement hook. Editing it would disarm the guards for every role, including this one -- which is why no role may, whatever the ownership map says. Raise it with the Orchestrator." ;;
    .claude/kit.yaml|.claude/kit.lock.json)
      kit_deny "Blocked: ${rel} is the kit profile every hook reads. Editing it rewrites the ownership map and the floors that bind you. Raise the change with the Orchestrator; the installer regenerates it." ;;
    .claude/settings.json)
      kit_deny "Blocked: ${rel} holds the permission rules, including the secret denies. It is generated from the profile, not edited by agents." ;;
  esac
  plan=$(kit_q '.spine.plan')
  if [ -n "$plan" ] && [ "$rel" = "${plan#./}" ]; then
    kit_deny "Blocked: ${rel} is the Orchestrator's dispatch state. Subagents never edit it -- emit a handoff note with /handoff instead."
  fi
  # A role must not rewrite the rulebook that binds it: strategy.md holds the floors
  # and the ownership map, and the register is the Orchestrator's by its own header.
  for key in strategy risks; do
    p=$(jq -r --arg k "$key" '.spine[$k] // empty | strings' "$KIT_LOCK" 2>/dev/null)
    if [ -n "$p" ] && [ "$rel" = "${p#./}" ]; then
      kit_deny "Blocked: ${rel} is the operating model, not an agent's to edit -- changing it would let you widen your own boundary or weaken a floor. Raise it with the Orchestrator."
    fi
  done
  # The documents the project arrived with. They are the user's statement of what is
  # being built; a role that may rewrite the PRD can make any task compliant by editing
  # what compliance means. A list, so it is looped rather than keyed.
  while IFS= read -r p; do
    [ -n "$p" ] || continue
    if [ "$rel" = "${p#./}" ]; then
      kit_deny "Blocked: ${rel} is an inherited project document -- the user's source of truth, not an agent's to rewrite. Propose the change in your handoff note and let the user make it."
    fi
  done <<<"$(kit_q '.spine.inherited[]?')"

  # Mine? Then fine. Another role's and not mine? Blocked. Unowned? Allowed.
  kit_match_glob "$mine" && continue
  while IFS= read -r line; do
    [ -n "$line" ] || continue
    other="${line%%|*}"
    if kit_match_glob "${line#*|}"; then
      kit_deny "Blocked: ${rel} is owned by \`${other}\`, not \`${role}\`. Request the change from ${other}, or ask the Orchestrator to split the task along the boundary."
    fi
  done <<<"$others"
done
exit 0
